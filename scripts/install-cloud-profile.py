#!/usr/bin/env python3
"""Install an exported Claude profile as content-addressed snapshots with owned links.

Never touches settings.json, .credentials.json, hooks, permissions, git config,
or anything under $HOME/.agents.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import stat
import sys
import tempfile


PROVENANCE = 'cloud-profile-provenance.json'
DEFAULT_CHECKOUT_ROOT = '/workspace/claude-settings'
REQUIRED_ROOTS = ('CLAUDE.md', 'skills', 'scripts')
OPTIONAL_ROOTS = ('web', 'commands', 'agents')
OWNED_ROOTS = REQUIRED_ROOTS + OPTIONAL_ROOTS
# Exported but never linked: documentation that travels with the snapshot.
PASSIVE_ROOTS = ('README.md', 'docs')
SHA256 = re.compile('[0-9a-f]{64}')


class ProfileError(ValueError):
    pass


def absolute(path):
    return Path(os.path.abspath(Path(path).expanduser()))


def safe_parents(path):
    for parent in path.parents:
        if parent.is_symlink():
            raise ProfileError(f'symlinked parent directory: {parent}')
        if os.path.lexists(parent) and not parent.is_dir():
            raise ProfileError(f'parent is not a directory: {parent}')


def require_real_dir(path, label):
    if os.path.lexists(path) and (path.is_symlink() or not path.is_dir()):
        raise ProfileError(f'{label} must be a real directory: {path}')


# Host-generated, never exported: Claude Code caches claude.ai account skills here.
HOST_WRITTEN_DIRS = (('skills', 'synced'),)


def ignorable(relative):
    """Bytecode and host-written caches inside the linked snapshot are not content."""
    return '__pycache__' in relative.parts or tuple(relative.parts[:2]) in HOST_WRITTEN_DIRS


def strict_json(path, label):
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ProfileError(f'duplicate key in {label}: {key}')
            result[key] = value
        return result
    if path.is_symlink() or not path.is_file():
        raise ProfileError(f'{label} must be a regular file: {path}')
    try:
        return json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=unique)
    except (json.JSONDecodeError, UnicodeError) as exc:
        raise ProfileError(f'malformed {label}: {path}') from exc


def validate_provenance(data, where):
    """Return [(relative path, mode, sha256)] from an exporter provenance document."""
    if not isinstance(data, dict) or data.get('format_version') != 1:
        raise ProfileError(f'unsupported provenance format: {where}')
    if not isinstance(data.get('source_revision'), str) or not isinstance(data.get('tracked_dirty'), bool):
        raise ProfileError(f'provenance lacks source_revision/tracked_dirty: {where}')
    files = data.get('files')
    if not isinstance(files, list) or not files:
        raise ProfileError(f'provenance has no files list: {where}')
    entries, seen = [], set()
    for item in files:
        if not isinstance(item, dict) or set(item) != {'path', 'sha256', 'mode'}:
            raise ProfileError(f'malformed provenance file entry in {where}: {item!r}')
        relative, digest, mode = item['path'], item['sha256'], item['mode']
        if not isinstance(relative, str) or not isinstance(digest, str) or not isinstance(mode, str):
            raise ProfileError(f'malformed provenance file entry in {where}: {item!r}')
        pure = PurePosixPath(relative)
        if (pure.is_absolute() or not pure.parts or str(pure) != relative or '\\' in relative
                or any(part in {'', '.', '..'} for part in pure.parts) or relative == PROVENANCE):
            raise ProfileError(f'unsafe provenance path in {where}: {relative!r}')
        top = pure.parts[0]
        if not (relative in {'CLAUDE.md', 'README.md'}
                or (len(pure.parts) > 1 and top in OWNED_ROOTS + ('docs',) and top != 'CLAUDE.md')):
            raise ProfileError(f'provenance path outside the profile roots in {where}: {relative}')
        if ignorable(Path(relative)):
            raise ProfileError(f'generated bytecode in provenance: {relative}')
        if not SHA256.fullmatch(digest) or not re.fullmatch('0?[0-7]{3}', mode):
            raise ProfileError(f'malformed provenance hash or mode in {where}: {relative}')
        if relative in seen:
            raise ProfileError(f'duplicate provenance path in {where}: {relative}')
        seen.add(relative)
        entries.append((relative, int(mode, 8), digest))
    for root in seen:
        parts = PurePosixPath(root).parts
        for depth in range(1, len(parts)):
            if '/'.join(parts[:depth]) in seen:
                raise ProfileError(f'provenance path is both file and directory: {root}')
    tops = {PurePosixPath(p).parts[0] for p in seen}
    if 'CLAUDE.md' not in seen or 'skills' not in tops or 'scripts' not in tops:
        raise ProfileError(f'export requires CLAUDE.md, skills/ and scripts/: {where}')
    return sorted(entries)


def content_version(entries):
    canonical = json.dumps([[path, mode, digest] for path, mode, digest in entries])
    return hashlib.sha256(canonical.encode()).hexdigest()


def verify_tree(root, entries, label):
    """Every listed file matches by hash and mode; nothing else lives in the tree."""
    expected = {Path(path): (mode, digest) for path, mode, digest in entries}
    parents = {parent for path in expected for parent in path.parents if parent != Path('.')}
    problems = []
    for dirpath, dirnames, filenames in os.walk(root):
        base = Path(dirpath)
        for name in dirnames + filenames:
            path = base / name
            relative = path.relative_to(root)
            if relative == Path(PROVENANCE) or ignorable(relative):
                continue
            info = path.lstat()
            if stat.S_ISLNK(info.st_mode):
                problems.append(f'symlink {relative}')
            elif stat.S_ISDIR(info.st_mode):
                if relative not in parents:
                    problems.append(f'unlisted directory {relative}')
            elif relative not in expected:
                problems.append(f'unlisted file {relative}')
            elif not stat.S_ISREG(info.st_mode):
                problems.append(f'nonregular file {relative}')
            else:
                mode, digest = expected[relative]
                if stat.S_IMODE(info.st_mode) != mode:
                    problems.append(f'mode changed {relative}')
                if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
                    problems.append(f'content changed {relative}')
        dirnames[:] = [d for d in dirnames if not (base / d).is_symlink()]
    for relative in expected:
        path = root / relative
        if not os.path.lexists(path):
            problems.append(f'missing {relative}')
    if problems:
        raise ProfileError(f'{label} does not match its provenance: ' + '; '.join(sorted(problems)[:10]))


def load_bundle(source):
    if source.is_symlink() or not source.is_dir():
        raise ProfileError(f'source must be a real directory: {source}')
    provenance = source / PROVENANCE
    if not os.path.lexists(provenance):
        raise ProfileError(f'not an export bundle (no {PROVENANCE}); run scripts/export-cloud-profile.py first: {source}')
    entries = validate_provenance(strict_json(provenance, 'provenance'), provenance)
    verify_tree(source, entries, f'export bundle {source}')
    return entries


def owned_roots(entries):
    tops = {PurePosixPath(path).parts[0] for path, _, _ in entries}
    return [name for name in OWNED_ROOTS if name in tops]


def read_manifest(manifest, persistent, current):
    if not os.path.lexists(manifest):
        return {}
    data = strict_json(manifest, 'ownership manifest')
    if not isinstance(data, dict):
        raise ProfileError(f'malformed ownership manifest: {manifest}')
    allowed = {str(persistent / name): str(current / name) for name in OWNED_ROOTS}
    for name, target in data.items():
        if allowed.get(name) != target:
            raise ProfileError(f'malformed ownership manifest entry: {name!r} -> {target!r}')
    return data


def matches(path, target):
    return path.is_symlink() and os.readlink(path) == target


def write_json(path, data):
    temporary = path.with_name(path.name + '.new')
    temporary.write_text(json.dumps(data, indent=2, sort_keys=True) + '\n')
    os.replace(temporary, path)


def install(home, source=None, check=False, adopt=False, checkout_root=DEFAULT_CHECKOUT_ROOT, installed_only=False):
    home = absolute(home)
    persistent = home / '.claude'
    storage = persistent / 'cloud-profile'
    snapshots = storage / 'snapshots'
    current = storage / 'current'
    manifest = storage / 'links.json'
    checkout_root = absolute(checkout_root)

    safe_parents(persistent / 'x')
    require_real_dir(persistent, 'profile directory')
    if os.path.lexists(persistent / '.git'):
        raise ProfileError(f'{persistent} is a git checkout; the cloud profile is for managed hosts only')
    for path in [storage, snapshots]:
        safe_parents(path)
        require_real_dir(path, 'profile storage')
    for path in [current.with_name('current.new'), manifest.with_name('links.json.new')]:
        if os.path.lexists(path):
            raise ProfileError(f'leftover update or concurrent install: {path}')

    installed = None
    if os.path.lexists(current):
        target = os.readlink(current) if current.is_symlink() else None
        if target is None or Path(target).parent != snapshots or not SHA256.fullmatch(Path(target).name):
            raise ProfileError(f'current is not a managed snapshot pointer: {current}')
        installed = Path(target)
        require_real_dir(installed, 'snapshot')

    if source is not None:
        source = absolute(source)
        if source == persistent or persistent in source.parents or source in persistent.parents:
            raise ProfileError(f'source and destination overlap: {source}')
        entries = load_bundle(source)
    elif check or installed_only:
        if installed is None or not installed.is_dir():
            raise ProfileError('no installed cloud profile; run initial setup first')
        entries = validate_provenance(strict_json(installed / PROVENANCE, 'snapshot provenance'), installed)
    else:
        raise ProfileError('--source is required unless --installed or --check is given')

    version = content_version(entries)
    if source is None and installed.name != version:
        raise ProfileError(f'tampered snapshot {installed}: provenance does not match its name')
    snapshot = snapshots / version
    reuse = os.path.lexists(snapshot)
    if reuse:
        require_real_dir(snapshot, 'snapshot')
        own = validate_provenance(strict_json(snapshot / PROVENANCE, 'snapshot provenance'), snapshot)
        if content_version(own) != version:
            raise ProfileError(f'tampered snapshot {snapshot}: provenance does not match its name')
        verify_tree(snapshot, own, f'tampered snapshot {snapshot}')

    if installed_only and not manifest.is_file():
        raise ProfileError('installed profile has no ownership manifest')
    previous = read_manifest(manifest, persistent, current)
    desired = {str(persistent / name): str(current / name) for name in owned_roots(entries)}
    conflicts, adoptions = [], []
    for name in sorted({**previous, **desired}):
        path = Path(name)
        safe_parents(path)
        if not os.path.lexists(path) or (name in previous and matches(path, previous[name])):
            continue
        if name not in desired:
            continue  # no longer wanted and not ours any more: forget it, never touch it
        relative = path.name
        recognized = (path.is_symlink() and os.path.isabs(os.readlink(path))
                      and os.path.normpath(os.readlink(path)) == str(checkout_root / relative))
        if recognized and adopt:
            adoptions.append(name)
            continue
        hint = ' (recognized checkout link; pass --adopt-checkout-links)' if recognized else ''
        conflicts.append(f'{path}{hint}')
    if conflicts:
        raise ProfileError('conflicting existing assets preserved, nothing changed:\n  ' + '\n  '.join(conflicts))

    print(f'Profile storage: {storage}')
    print(f'Snapshot: {snapshot}')
    for name, target in desired.items():
        print(f'Link: {name} -> {target}')

    if check:
        if installed != snapshot:
            raise ProfileError(f'installed snapshot {installed} does not match {snapshot}; rerun bootstrap')
        if previous != desired:
            raise ProfileError('ownership manifest does not match the installed snapshot; rerun bootstrap')
        for name, target in desired.items():
            if not matches(Path(name), target) or not Path(name).exists():
                raise ProfileError(f'missing or broken owned link: {name}')
        print(f'Profile verified: {version}; host instruction loading and skill discovery are NOT verified')
        return version

    storage.mkdir(parents=True, exist_ok=True)
    snapshots.mkdir(exist_ok=True)
    if not reuse:
        stage = Path(tempfile.mkdtemp(prefix='.stage-', dir=snapshots))
        try:
            for relative, mode, _ in entries:
                target = stage / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes((source / relative).read_bytes())
                os.chmod(target, mode)
            shutil.copyfile(source / PROVENANCE, stage / PROVENANCE)
            os.chmod(stage / PROVENANCE, 0o644)
            verify_tree(stage, entries, 'staged snapshot')
            os.chmod(stage, 0o755)
            stage.rename(snapshot)
        finally:
            if stage.exists():
                shutil.rmtree(stage)
    pointer = current.with_name('current.new')
    pointer.symlink_to(snapshot)
    os.replace(pointer, current)
    # Record ownership before creating links so an interrupted run can resume.
    write_json(manifest, {**previous, **desired})
    for name, target in desired.items():
        path = Path(name)
        if name in adoptions:
            path.unlink()
        if not os.path.lexists(path):
            path.symlink_to(target)
    for name, target in previous.items():
        if name not in desired and matches(Path(name), target):
            Path(name).unlink()
    write_json(manifest, desired)
    print(f'Cloud profile installed: {version}' + (' (reused snapshot)' if reuse else ''))
    print('Preserved settings.json, .credentials.json, hooks, permissions, git config and $HOME/.agents.')
    return version


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--home', type=Path, default=Path.home(), help='persistent home (default: $HOME)')
    source_group = parser.add_mutually_exclusive_group()
    source_group.add_argument('--source', type=Path, help=f'export bundle containing {PROVENANCE}')
    source_group.add_argument('--installed', action='store_true',
                              help='restore/check links from the persistent snapshot without fetching source')
    parser.add_argument('--check', action='store_true', help='verify only; never modify anything')
    parser.add_argument('--adopt-checkout-links', action='store_true',
                        help='replace links that point exactly into the recognized checkout')
    parser.add_argument('--checkout-root', type=Path, default=Path(DEFAULT_CHECKOUT_ROOT),
                        help=f'recognized checkout root (default: {DEFAULT_CHECKOUT_ROOT})')
    args = parser.parse_args(argv)
    try:
        install(args.home, args.source, args.check, args.adopt_checkout_links, args.checkout_root, args.installed)
    except (ValueError, OSError) as exc:
        parser.exit(1, f'cloud-profile: {exc}\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
